//! `azra pkg`: manifests, a local registry, dependency installation and a
//! lockfile. Everything is file-based, so a project can be shared without a
//! network connection; registry packages are simply versioned folders.

use crate::manifest::{self, Dependency, Manifest};
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

pub struct RegistryEntry {
    pub name: String,
    pub version: String,
    pub dir: String,
}

pub fn registry_root() -> PathBuf {
    if let Ok(dir) = std::env::var("AZRA_REGISTRY") {
        return PathBuf::from(dir);
    }
    let home = std::env::var("USERPROFILE")
        .or_else(|_| std::env::var("HOME"))
        .unwrap_or_else(|_| ".".to_string());
    PathBuf::from(home).join(".azra").join("registry")
}

fn index_path() -> PathBuf {
    registry_root().join("index.toml")
}

fn lock_path(project: &Path) -> PathBuf {
    project.join("azra.lock")
}

fn manifest_path(project: &Path) -> PathBuf {
    project.join("azra.toml")
}

fn read_manifest(project: &Path) -> Result<Manifest, String> {
    let path = manifest_path(project);
    let text =
        fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {}", path.display(), e))?;
    Ok(Manifest::parse(&text))
}

pub fn init(project: &Path, name: &str) -> Result<String, String> {
    let manifest = Manifest {
        name: name.to_string(),
        version: "0.1.0".to_string(),
        description: String::new(),
        entry: "main.vibe".to_string(),
        dependencies: Vec::new(),
    };
    fs::write(manifest_path(project), manifest.render())
        .map_err(|e| format!("cannot write azra.toml: {e}"))?;
    let main = project.join("main.vibe");
    if !main.exists() {
        fs::write(
            &main,
            "note: generated by `azra init`\nsay \"Hello from Azra!\"\n",
        )
        .map_err(|e| format!("cannot write main.vibe: {e}"))?;
    }
    Ok(format!(
        "initialized Azra package `{name}` in {}",
        project.display()
    ))
}

// ------------------------------------------------------------------- registry

fn read_index() -> Vec<RegistryEntry> {
    let path = index_path();
    let Ok(text) = fs::read_to_string(path) else {
        return Vec::new();
    };
    let toml = manifest::parse(&text);
    toml.entries("package")
        .into_iter()
        .filter_map(|entry| {
            Some(RegistryEntry {
                name: entry.get("name")?.as_str()?.to_string(),
                version: entry.get("version")?.as_str()?.to_string(),
                dir: entry
                    .get("dir")
                    .and_then(manifest::Value::as_str)
                    .unwrap_or("")
                    .to_string(),
            })
        })
        .collect()
}

fn write_index(entries: &[RegistryEntry]) -> Result<(), String> {
    let root = registry_root();
    fs::create_dir_all(&root).map_err(|e| e.to_string())?;
    let mut text = String::from("# Azra local registry index\n");
    for entry in entries {
        text.push_str("\n[[package]]\n");
        text.push_str(&format!("name = {}\n", manifest::quote(&entry.name)));
        text.push_str(&format!("version = {}\n", manifest::quote(&entry.version)));
        text.push_str(&format!("dir = {}\n", manifest::quote(&entry.dir)));
    }
    fs::write(index_path(), text).map_err(|e| e.to_string())
}

pub fn publish(dir: &Path) -> Result<String, String> {
    let manifest = read_manifest(dir)?;
    if manifest.name.is_empty() {
        return Err("package name must not be empty".to_string());
    }
    let target = registry_root()
        .join("packages")
        .join(&manifest.name)
        .join(&manifest.version);
    fs::create_dir_all(&target).map_err(|e| e.to_string())?;
    let mut copies = 0;
    for item in fs::read_dir(dir).map_err(|e| e.to_string())? {
        let item = item.map_err(|e| e.to_string())?;
        let path = item.path();
        if path.is_file()
            && path
                .extension()
                .is_some_and(|ext| ext.eq_ignore_ascii_case("vibe"))
        {
            fs::copy(&path, target.join(item.file_name())).map_err(|e| e.to_string())?;
            copies += 1;
        }
    }
    fs::write(target.join("azra.toml"), manifest.render()).map_err(|e| e.to_string())?;
    let mut entries = read_index();
    entries.retain(|e| !(e.name == manifest.name && e.version == manifest.version));
    entries.push(RegistryEntry {
        name: manifest.name.clone(),
        version: manifest.version.clone(),
        dir: format!("{}/{}", manifest.name, manifest.version),
    });
    write_index(&entries)?;
    Ok(format!(
        "published {}@{} ({} .vibe file(s)) to {}",
        manifest.name,
        manifest.version,
        copies,
        target.display()
    ))
}

pub fn registry_list() -> Result<String, String> {
    let entries = read_index();
    if entries.is_empty() {
        return Ok(format!(
            "registry is empty ({}); use `azra pkg publish <dir>`",
            registry_root().display()
        ));
    }
    let mut lines = vec![format!("registry at {}", registry_root().display())];
    for entry in entries {
        lines.push(format!("  {}@{}", entry.name, entry.version));
    }
    Ok(lines.join("\n"))
}

// ------------------------------------------------------------------ manifest edits

fn parse_spec(spec: &str) -> (String, Option<String>) {
    match spec.split_once('@') {
        Some((name, version)) => (name.to_string(), Some(version.to_string())),
        None => (spec.to_string(), None),
    }
}

pub fn add(project: &Path, spec: &str) -> Result<String, String> {
    let mut manifest = read_manifest(project)?;
    let (name, version) = parse_spec(spec);
    if name.is_empty() {
        return Err("package name must not be empty".to_string());
    }
    manifest.dependencies.retain(|dep| dep.name != name);
    manifest.dependencies.push(Dependency {
        name: name.clone(),
        version: version.clone().or_else(|| Some("*".to_string())),
        path: None,
    });
    fs::write(manifest_path(project), manifest.render()).map_err(|e| e.to_string())?;
    Ok(format!(
        "added dependency `{name}` ({})",
        version.unwrap_or_default()
    ))
}

pub fn remove(project: &Path, name: &str) -> Result<String, String> {
    let mut manifest = read_manifest(project)?;
    let before = manifest.dependencies.len();
    manifest.dependencies.retain(|dep| dep.name != name);
    fs::write(manifest_path(project), manifest.render()).map_err(|e| e.to_string())?;
    Ok(format!(
        "{} dependency `{name}`",
        if manifest.dependencies.len() < before {
            "removed"
        } else {
            "no such"
        }
    ))
}

// --------------------------------------------------------------------- install

#[derive(Clone)]
struct LockEntry {
    name: String,
    version: String,
    source: String,
    path: String,
    depends: Vec<String>,
}

fn copy_dir(from: &Path, to: &Path) -> Result<(), String> {
    fs::create_dir_all(to).map_err(|e| e.to_string())?;
    for item in fs::read_dir(from).map_err(|e| e.to_string())? {
        let item = item.map_err(|e| e.to_string())?;
        let target = to.join(item.file_name());
        if item.path().is_dir() {
            copy_dir(&item.path(), &target)?;
        } else {
            fs::copy(item.path(), &target).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

fn locate_dependency(
    project: &Path,
    dep: &Dependency,
) -> Result<(PathBuf, String, String), String> {
    if let Some(path) = &dep.path {
        let source = if path.is_absolute() {
            path.clone()
        } else {
            project.join(path)
        };
        let manifest = read_manifest(&source)?;
        return Ok((source, manifest.version, "path".to_string()));
    }
    let requirement = dep.version.as_deref().unwrap_or("*");
    let index = read_index();
    let found = index
        .iter()
        .filter(|entry| {
            entry.name == dep.name && manifest::version_matches(requirement, &entry.version)
        })
        .max_by_key(|entry| {
            let mut it = entry
                .version
                .split('.')
                .map(|s| s.parse::<u64>().unwrap_or(0));
            (
                it.next().unwrap_or(0),
                it.next().unwrap_or(0),
                it.next().unwrap_or(0),
            )
        })
        .ok_or_else(|| {
            format!(
                "no registry package `{}` matching `{requirement}`; publish it first",
                dep.name
            )
        })?;
    Ok((
        registry_root().join("packages").join(&found.dir),
        found.version.clone(),
        "registry".to_string(),
    ))
}

pub fn install(project: &Path) -> Result<String, String> {
    let root_manifest = read_manifest(project)?;
    let packages = project.join(".azra").join("packages");
    fs::create_dir_all(&packages).map_err(|e| e.to_string())?;
    let mut installed: Vec<LockEntry> = Vec::new();
    let mut visited = BTreeSet::new();

    fn visit(
        owner: &Path,
        deps: &[Dependency],
        packages: &Path,
        visited: &mut BTreeSet<String>,
        installed: &mut Vec<LockEntry>,
    ) -> Result<(), String> {
        for dep in deps {
            let (source, version, source_kind) = locate_dependency(owner, dep)?;
            let id = format!("{}@{}", dep.name, version);
            let dest = packages.join(&id);
            let depends: Vec<String> = source
                .join("azra.toml")
                .exists()
                .then(|| {
                    read_manifest(&source).map(|m| {
                        m.dependencies
                            .iter()
                            .map(|d| format!("{}@{}", d.name, d.version.as_deref().unwrap_or("*")))
                            .collect()
                    })
                })
                .transpose()?
                .unwrap_or_default();
            if !dest.exists() {
                copy_dir(&source, &dest).map_err(|e| format!("cannot install {id}: {e}"))?;
            }
            if visited.insert(id.clone()) {
                installed.push(LockEntry {
                    name: dep.name.clone(),
                    version,
                    source: source_kind,
                    path: format!(".azra/packages/{id}"),
                    depends,
                });
                if let Ok(child) = read_manifest(&dest) {
                    visit(&dest, &child.dependencies, packages, visited, installed)?;
                }
            }
        }
        Ok(())
    }

    visit(
        project,
        &root_manifest.dependencies,
        &packages,
        &mut visited,
        &mut installed,
    )?;

    let mut lock = String::from("# Azra lockfile — generated by `azra pkg install`\n");
    for entry in &installed {
        lock.push_str("\n[[package]]\n");
        lock.push_str(&format!("name = {}\n", manifest::quote(&entry.name)));
        lock.push_str(&format!("version = {}\n", manifest::quote(&entry.version)));
        lock.push_str(&format!("source = {}\n", manifest::quote(&entry.source)));
        lock.push_str(&format!("path = {}\n", manifest::quote(&entry.path)));
        lock.push_str(&format!(
            "depends = {}\n",
            manifest::quote(&entry.depends.join(", "))
        ));
    }
    fs::write(lock_path(project), lock).map_err(|e| e.to_string())?;
    Ok(format!(
        "installed {} package(s); wrote {}",
        installed.len(),
        lock_path(project).display()
    ))
}

pub fn tree(project: &Path) -> Result<String, String> {
    let text = fs::read_to_string(lock_path(project))
        .map_err(|e| format!("no lockfile (run `azra pkg install`): {e}"))?;
    let toml = manifest::parse(&text);
    let entries = toml.entries("package");
    if entries.is_empty() {
        return Ok(format!(
            "{} (no dependencies)",
            read_manifest(project)?.name
        ));
    }
    let mut lines = vec![read_manifest(project)?.name];
    for entry in entries {
        let name = entry
            .get("name")
            .and_then(manifest::Value::as_str)
            .unwrap_or("?");
        let version = entry
            .get("version")
            .and_then(manifest::Value::as_str)
            .unwrap_or("?");
        let source = entry
            .get("source")
            .and_then(manifest::Value::as_str)
            .unwrap_or("?");
        lines.push(format!("├── {name}@{version} [{source}]"));
    }
    Ok(lines.join("\n"))
}

/// All installed package directories, used by the module resolver.
pub fn package_dirs(project: &Path) -> Vec<PathBuf> {
    let root = project.join(".azra").join("packages");
    let Ok(items) = fs::read_dir(root) else {
        return Vec::new();
    };
    items
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect()
}
